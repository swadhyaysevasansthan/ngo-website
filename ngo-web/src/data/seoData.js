export const getSEOByPath = (pathname) => {
  // Exact match
  if (seoDataByPath[pathname]) {
    return seoDataByPath[pathname];
  }

  // Remove trailing slash if any
  const normalized = pathname.endsWith("/") && pathname.length > 1 
    ? pathname.slice(0, -1) 
    : pathname;

  if (seoDataByPath[normalized]) {
    return seoDataByPath[normalized];
  }

  // Dynamic route patterns
  if (normalized.startsWith("/community/")) {
    const slug = normalized.replace("/community/", "");
    const titleCase = slug.split("-").map(w => w.charAt(0).toUpperCase() + w.slice(1)).join(" ");
    return {
      title: `${titleCase} Initiative | Swadhyay Seva Foundation`,
      description: `Learn about the ${titleCase} community initiative by Swadhyay Seva Foundation, promoting sustainable development and ecological wellness.`,
      keywords: `${slug}, ${titleCase}, Swadhyay community, ecological initiative`
    };
  }

  if (normalized.startsWith("/innovative-farmers/")) {
    return {
      title: "Farmer Profile | Innovative Farmers Network | Swadhyay Seva Foundation",
      description: "Discover the journey and regenerative farming practices of this progressive natural farmer supported by Swadhyay Seva Foundation.",
      keywords: "farmer profile, natural farming hero, organic agriculture, sustainable farming"
    };
  }

  if (normalized.startsWith("/yoga-team/")) {
    return {
      title: "Yoga Instructor Profile | Swadhyay Seva Foundation",
      description: "Meet our certified yoga instructor and explore their experience, teaching philosophy, and wellness classes.",
      keywords: "yoga instructor profile, certified yogi, pranayama teacher, meditation guide"
    };
  }

  return defaultSEO;
};
